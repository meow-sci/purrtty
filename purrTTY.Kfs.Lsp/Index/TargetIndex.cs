using System.Globalization;
using KSA.Kfs.KAsm;
using KSA.Kfs.KC;
using KSA.Kfs.Vm.Tables;

namespace purrTTY.Kfs.Lsp.Index;

/// <summary>
/// Everything of plan §6.5 that depends on the vehicle layout of the build target: the names of
/// <c>&lt;vehicle.h&gt;</c> (<c>KFS_LAYOUT_FINGERPRINT</c>, <c>THRUSTER_COUNT</c>…, <c>MSG_*</c>, the
/// generated typedefs), the members of <c>commands</c>, <c>sensors</c> and every message struct with
/// their types, offsets and units (<c>MessageLayout</c>, <c>layout.CommandFields</c>,
/// <c>tables.MessagesData</c>), and <c>&lt;vehicle.kinc&gt;</c>'s constants and types. Immutable.
/// </summary>
public sealed class TargetIndex
{
    private TargetIndex() { }

    /// <summary>The target's name (<c>bench</c>, <c>vehicle 12</c>).</summary>
    public string TargetName { get; private set; } = "";

    /// <summary>The scanned <c>&lt;vehicle.h&gt;</c>.</summary>
    public HeaderIndex VehicleHeader { get; private set; } = null!;

    /// <summary>kC names of <c>&lt;vehicle.h&gt;</c>, message names enriched from the message catalogue.</summary>
    public IReadOnlyDictionary<string, IndexEntry> KcNames { get; private set; } = null!;

    /// <summary>kASM symbols of <c>&lt;vehicle.kinc&gt;</c>.</summary>
    public IReadOnlyDictionary<string, IndexEntry> KasmNames { get; private set; } = null!;

    /// <summary>kASM types of <c>&lt;vehicle.kinc&gt;</c>.</summary>
    public IReadOnlyDictionary<string, IndexEntry> KasmTypes { get; private set; } = null!;

    /// <summary>Struct shapes by C type name: <c>kfs_commands_t</c>, <c>kfs_sensors_t</c>, message structs and their element types, <c>kfs_msg_header_t</c>.</summary>
    public IReadOnlyDictionary<string, MemberShape> Shapes { get; private set; } = null!;

    /// <summary>The objects of <c>&lt;vehicle.h&gt;</c> with a shape: <c>commands</c>, <c>sensors</c> (when the layout has them).</summary>
    public IReadOnlyDictionary<string, MemberShape> Roots { get; private set; } = null!;

    /// <summary>The message names (<c>MSG_FLIGHT_DATA</c>) with their struct type names.</summary>
    public IReadOnlyDictionary<string, string> MessageTypes { get; private set; } = null!;

    /// <summary>Builds the index for <paramref name="layout"/> on <paramref name="tables"/>.</summary>
    public static TargetIndex Build(GameTables tables, IoLayout layout, string targetName)
    {
        ArgumentNullException.ThrowIfNull(tables);
        ArgumentNullException.ThrowIfNull(layout);
        var index = new TargetIndex { TargetName = targetName };
        index.Fill(tables, layout);
        return index;
    }

    private void Fill(GameTables tables, IoLayout layout)
    {
        string header = KSA.Kfs.KC.VehicleHeader.Generate(layout, false, tables);
        VehicleHeader = HeaderIndex.Scan([new("vehicle.h", header)], describe: _ =>
            $"Generated by kFS for the build target ({TargetName}, layout 0x{layout.Fingerprint:X8}): the command and sensor blocks, the group counts, the message ids and structs.");
        var kc = new Dictionary<string, IndexEntry>(VehicleHeader.Names, StringComparer.Ordinal);
        var shapes = new Dictionary<string, MemberShape>(StringComparer.Ordinal);
        var roots = new Dictionary<string, MemberShape>(StringComparer.Ordinal);
        string where = $"`<vehicle.h>` for {TargetName}";

        // The count defines: say where the number comes from.
        foreach (string group in new[] { "thruster", "engine", "gimbal" })
        {
            string name = group.ToUpperInvariant() + "_COUNT";
            if (!kc.TryGetValue(name, out IndexEntry? define)) continue;
            int count = MessageLayout.GroupCount(layout, group);
            kc[name] = define with
            {
                Documentation = Markup.Join($"The number of {group}s of the build target ({TargetName}): {count}. " +
                    $"`commands.{group}[0 … {Math.Max(0, count - 1)}]`" + (count == 0 ? " does not exist on this target." : " are its command slots."),
                    $"Defined in {where}; it changes with the target (`kfs target`)."),
            };
        }
        if (kc.TryGetValue("KFS_LAYOUT_FINGERPRINT", out IndexEntry? fp))
            kc["KFS_LAYOUT_FINGERPRINT"] = fp with { Documentation = Markup.Join($"The CRC-32 fingerprint of the I/O layout of {TargetName}: an image built for another layout does not load.", $"Defined in {where}.") };

        // Command and sensor blocks.
        if (layout.CommandFields.Length > 0)
        {
            ShapeBuilder.Node tree = ShapeBuilder.Tree(layout.CommandFields.Select(f => new ShapeBuilder.Leaf(f.Name, f.Type, f.Offset, f.OneShot)));
            MemberShape commands = ShapeBuilder.ToShape(tree, "kfs_commands_t", n => DescribeBlock(n, "command", 0x90000000u, layout, TargetName), n => $"kfs_{n.Name}_cmd_t");
            shapes["kfs_commands_t"] = commands;
            foreach (ShapeMember m in commands.Members) if (m.Shape is { } s) shapes[s.TypeName] = s;
            roots["commands"] = commands;
            if (kc.TryGetValue("commands", out IndexEntry? decl))
                kc["commands"] = decl with { Documentation = Markup.Join($"The command block of {TargetName} at 0x90000000 (written by a program that claims `ALLOCATION`). Members: {string.Join(", ", commands.Members.Select(m => Markup.Code(m.Name + (m.Entry.Detail.EndsWith(']') ? "[]" : ""))))}.", $"Declared in {where}.") };
        }
        if (layout.SensorFields.Length > 0)
        {
            ShapeBuilder.Node tree = ShapeBuilder.Tree(layout.SensorFields.Select(f => new ShapeBuilder.Leaf(f.Name, f.Type, f.Offset, f.OneShot)));
            MemberShape sensors = ShapeBuilder.ToShape(tree, "kfs_sensors_t", n => DescribeBlock(n, "sensor", 0x80000000u, layout, TargetName), n => $"kfs_{n.Name}_t");
            shapes["kfs_sensors_t"] = sensors;
            foreach (ShapeMember m in sensors.Members) if (m.Shape is { } s) shapes[s.TypeName] = s;
            roots["sensors"] = sensors;
            if (kc.TryGetValue("sensors", out IndexEntry? decl))
                kc["sensors"] = decl with { Documentation = Markup.Join($"The read-only sensor block of {TargetName} at 0x80000000. Members: {string.Join(", ", sensors.Members.Select(m => Markup.Code(m.Name)))}.", $"Declared in {where}.") };
        }

        // Messages.
        var messageTypes = new Dictionary<string, string>(StringComparer.Ordinal);
        var header16 = MessageLayout.Header.Select(l => new ShapeBuilder.Leaf(l.Path["hdr.".Length..], l.Type, l.Offset));
        shapes["kfs_msg_header_t"] = ShapeBuilder.ToShape(ShapeBuilder.Tree(header16), "kfs_msg_header_t", HeaderMember);
        foreach (MessageRow row in tables.MessagesData.Messages)
        {
            MessageLayout message = MessageLayout.Build(row, layout);
            messageTypes[message.Name] = message.TypeName;
            var meanings = new Dictionary<string, (string Type, string Meaning)>(StringComparer.Ordinal);
            foreach (MessageFieldRow field in row.Fields)
            {
                foreach (string name in field.Names) meanings[name.EndsWith("[i]", StringComparison.Ordinal) ? name[..^3] : name] = (field.Type, field.Meaning);
            }
            var memberTypes = message.Members.ToDictionary(m => m.Name, m => m.TypeName, StringComparer.Ordinal);
            var elementTypes = message.ElementTypes.ToDictionary(e => e.TypeName, StringComparer.Ordinal);
            ShapeBuilder.Node tree = ShapeBuilder.Tree(message.Leaves.Select(l => new ShapeBuilder.Leaf(l.Path, l.Type, l.Offset)));
            MemberShape shape = ShapeBuilder.ToShape(tree, message.TypeName,
                n => DescribeMessageField(n, message, meanings, memberTypes, elementTypes),
                n => ChildType(n, memberTypes, elementTypes));
            shapes[message.TypeName] = shape;
            foreach (ShapeMember m in shape.Members)
            {
                if (m.Shape is { } s && s.TypeName.StartsWith("kfs_vehicle_props_", StringComparison.Ordinal)) shapes[s.TypeName] = s;
            }

            string fields = string.Join(", ", shape.Members.Where(m => m.Name != "hdr").Take(10).Select(m => Markup.Code(m.Name)));
            string doc = Markup.Join(
                $"Message `{row.Id}` {message.Name} (catalogue §{row.Section}): struct `{message.TypeName}`, {message.Size} bytes ({message.BodySize} after the 16-byte header){(message.PerVehicle ? ", per vehicle: its size follows the layout" : "")}.",
                $"Fields: {fields}{(shape.Members.Count > 11 ? ", …" : "")}.",
                MessageLayout.HostPublished.Contains(message.Name) ? "Published by the host." : null,
                $"Use it with `#pragma kfs subscribe {message.Name} buffer` / `publish`; defined in {where}.");
            if (kc.TryGetValue(message.Name, out IndexEntry? define)) kc[message.Name] = define with { Documentation = doc };
            if (kc.TryGetValue(message.TypeName, out IndexEntry? type)) kc[message.TypeName] = type with { Documentation = Markup.Join(doc, $"Defined in {where}.") };
        }
        foreach ((string name, MemberShape shape) in new[] { ("vec3", "float"), ("quat", "float"), ("dvec3", "double"), ("dquat", "double") }
                     .Select(v => (v.Item1, ShapeBuilder.Vector(v.Item1, v.Item2, v.Item1.EndsWith("quat", StringComparison.Ordinal) ? ["x", "y", "z", "w"] : ["x", "y", "z"]))))
            shapes[name] = shape;
        shapes["mat3"] = ShapeBuilder.Matrix("mat3", "float");
        shapes["dmat3"] = ShapeBuilder.Matrix("dmat3", "double");

        // <vehicle.kinc>.
        var builtin = new BuiltinIncludes(tables, layout, "vehicle.kinc");
        var kasm = new Dictionary<string, IndexEntry>(StringComparer.Ordinal);
        foreach ((string name, long value) in builtin.Constants)
        {
            string text = name.StartsWith("MSG_", StringComparison.Ordinal) || name == "commands" || name == "sensors" ? $"0x{value:X}" : value.ToString(CultureInfo.InvariantCulture);
            string? doc = kc.TryGetValue(name, out IndexEntry? same) ? same.Documentation : null;
            if (name.Contains('.'))
            {
                string block = name[..name.IndexOf('.')];
                doc = roots.TryGetValue(block, out MemberShape? root) && root.Find(name[(block.Length + 1)..]) is { } member ? member.Entry.Documentation : null;
                text = $"0x{value:X8}";
            }
            kasm[name] = new IndexEntry(name, EntryKind.Constant, "= " + text, $".include <vehicle.kinc>\n.equ {name}, {text}",
                Markup.Join(doc ?? "", $"From `<vehicle.kinc>` for {TargetName}."), "kasm")
            {
                Origin = "vehicle.kinc",
                SortGroup = 3,
            };
        }
        var types = new Dictionary<string, IndexEntry>(StringComparer.Ordinal);
        foreach ((string name, AsmType type) in builtin.Types)
        {
            types[name] = new IndexEntry(name, EntryKind.Type, $"size {type.Size}, align {type.Align}", null,
                $"kASM type {Markup.Code(name)} of `<vehicle.kinc>` for {TargetName}: size {type.Size}, align {type.Align}, {type.Fields.Count} fields (`offsetof({name}, …)`).")
            {
                Origin = "vehicle.kinc",
                SortGroup = 4,
            };
        }

        KcNames = kc;
        KasmNames = kasm;
        KasmTypes = types;
        Shapes = shapes;
        Roots = roots;
        MessageTypes = messageTypes;
    }

    private static (string, string) DescribeBlock(ShapeBuilder.Node n, string block, uint baseAddress, IoLayout layout, string target)
    {
        if (n.Children.Count > 0)
        {
            string type = block == "command" && n.Path == n.Name ? $"kfs_{n.Name}_cmd_t" : block == "sensor" && n.Path == n.Name ? $"kfs_{n.Name}_t" : "struct";
            string count = n.Dimensions.Count > 0 ? $"{n.Dimensions[0]} on {target}" + (block == "command" ? $" (`{n.Name.ToUpperInvariant()}_COUNT`)" : "") : "";
            string structUnit = Markup.UnitOf(n.Name) is { } su ? $" Unit: {su}." : "";
            return (type, Markup.Join(
                (n.Dimensions.Count > 0 ? $"An array of {type}: {count}." : $"A struct of the {block} block at offset {n.Offset}.") + structUnit,
                $"Members: {string.Join(", ", n.Children.Select(c => Markup.Code(c.Name)))}."));
        }
        string ctype = ShapeBuilder.CType(n.LeafType ?? "");
        string unit = Markup.UnitOf(n.Name) is { } u ? $" Unit: {u}." : "";
        string oneShot = n.OneShot ? " One-shot: zeroed at the end of every tick, so write it in each tick it should act." : "";
        string first = n.Path.Contains('.') ? " (in the first element)" : "";
        return (ctype, Markup.Join($"A {Markup.Code(ctype)} field of the {block} block at offset {n.Offset}{first}, address 0x{baseAddress + (uint)n.Offset:X8}.{unit}{oneShot}",
            $"From the layout of {target}."));
    }

    private static (string, string) HeaderMember(ShapeBuilder.Node n) =>
        (ShapeBuilder.CType(n.LeafType ?? ""), $"Field of the 16-byte message header (`kfs_msg_header_t`) at offset {n.Offset}.");

    private static (string, string) DescribeMessageField(ShapeBuilder.Node n, MessageLayout message, Dictionary<string, (string Type, string Meaning)> meanings,
        Dictionary<string, string> memberTypes, Dictionary<string, MessageElementType> elementTypes)
    {
        string top = n.Path.Split('.')[0];
        bool isTop = top == n.Path;
        string ctype = n.Children.Count > 0 || isTop ? ChildType(n, memberTypes, elementTypes) : ShapeBuilder.CType(n.LeafType ?? "");
        if (n.Children.Count == 0 && n.LeafType is { } leaf && (ctype == "struct" || isTop && !memberTypes.ContainsKey(n.Name))) ctype = ShapeBuilder.CType(leaf);
        if (isTop && memberTypes.TryGetValue(n.Name, out string? memberType)) ctype = memberType;
        string? unit = n.Path.Split('.').Reverse().Select(Markup.UnitOf).FirstOrDefault(u => u is not null);
        var parts = new List<string?>();
        if (top == "hdr")
        {
            parts.Add(isTop ? "The 16-byte message header: `seq`, `source`, `flags`, `t_us`." : $"Header field at offset {n.Offset}.");
        }
        else if (meanings.TryGetValue(top, out var row))
        {
            if (isTop) parts.Add(row.Meaning.Length > 0 ? row.Meaning : null);
            else parts.Add($"Member of `{top}`" + (row.Meaning.Length > 0 ? $": {row.Meaning}" : "."));
        }
        if (unit is not null) parts.Add($"Unit: {unit} (from the name's suffix).");
        string count = n.Dimensions.Count > 0 ? $", {n.Dimensions[0]} element{(n.Dimensions[0] == 1 ? "" : "s")} on this layout" : "";
        parts.Add($"Offset {n.Offset}{(n.Path.Contains('.') ? " (first element)" : "")} in `{message.TypeName}`{count}.");
        return (ctype, Markup.Join(parts.ToArray()));
    }

    private static string ChildType(ShapeBuilder.Node n, Dictionary<string, string> memberTypes, Dictionary<string, MessageElementType> elementTypes)
    {
        string[] path = n.Path.Split('.');
        if (path.Length == 1) return memberTypes.GetValueOrDefault(n.Name) ?? "struct";
        if (path.Length == 2 && memberTypes.TryGetValue(path[0], out string? parent) && elementTypes.TryGetValue(parent, out MessageElementType? element))
            return element.Members.FirstOrDefault(m => m.Name == n.Name)?.TypeName ?? "struct";
        return "struct";
    }
}
