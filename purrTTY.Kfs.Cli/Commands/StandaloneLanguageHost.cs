namespace purrTTY.Kfs.Cli.Commands;

/// <summary>
/// Recovers the build target the game's workbench last wrote into a <c>vehicle.h</c>
/// (<c>GeneratedHeaders.VehicleH</c>: a three-line banner naming the target, the part and the layout
/// fingerprint, then <c>VehicleHeader.Generate</c>'s text with <c>KFS_LAYOUT_FINGERPRINT</c> and the
/// <c>THRUSTER_COUNT</c> / <c>ENGINE_COUNT</c> / <c>GIMBAL_COUNT</c> defines). The bench layout is
/// recognised by its fingerprint; a vehicle layout is rebuilt with <c>LayoutGenerator.Vehicle</c> from
/// the three counts (it is a pure function of them) and accepted only when the rebuilt fingerprint
/// equals the header's — and the banner's, when there is a banner.
/// </summary>
public static partial class VehicleHeaderLayout
{
    /// <summary>The target recorded in <paramref name="text"/>, or null with the reason it was rejected.</summary>
    public static BuildTarget? Reconstruct(string text, GameTables tables, out string reason)
    {
        ArgumentNullException.ThrowIfNull(text);
        ArgumentNullException.ThrowIfNull(tables);
        text = text.Replace("\r\n", "\n");

        Match banner = Banner().Match(text);
        uint? bannerFingerprint = banner.Success ? uint.Parse(banner.Groups["fp"].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture) : null;
        string target = banner.Success ? banner.Groups["target"].Value : "vehicle";
        string partName = banner.Success ? banner.Groups["part"].Value : tables.BenchPart.Name;

        Match fingerprintDefine = FingerprintDefine().Match(text);
        if (!fingerprintDefine.Success)
        {
            reason = "it has no '#define KFS_LAYOUT_FINGERPRINT 0x…u' line";
            return null;
        }
        uint fingerprint = uint.Parse(fingerprintDefine.Groups["fp"].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        if (bannerFingerprint is { } b && b != fingerprint)
        {
            reason = $"its banner says layout 0x{b:X8} but KFS_LAYOUT_FINGERPRINT is 0x{fingerprint:X8}";
            return null;
        }

        PartDescription part;
        string partNote = "";
        try
        {
            part = tables.Part(partName);
        }
        catch (GameTablesException)
        {
            part = tables.BenchPart;
            partNote = $"; its part '{partName}' is unknown to these tables, so the {part.Name} part is used";
        }

        if (fingerprint == tables.BenchLayout.Fingerprint)
        {
            reason = "the bench layout" + partNote;
            return new BuildTarget(part, tables.BenchLayout, $"{target} (from vehicle.h)");
        }

        int? thrusters = Count(text, "THRUSTER"), engines = Count(text, "ENGINE"), gimbals = Count(text, "GIMBAL");
        if (thrusters is null || engines is null || gimbals is null)
        {
            reason = "it lacks one of the THRUSTER_COUNT, ENGINE_COUNT and GIMBAL_COUNT defines";
            return null;
        }
        if (thrusters > 4096 || engines > 4096 || gimbals > 4096)
        {
            reason = "its counts are implausibly large";
            return null;
        }
        IoLayout layout;
        try
        {
            layout = LayoutGenerator.Vehicle(target, thrusters.Value, engines.Value, gimbals.Value);
        }
        catch (Exception e) when (e is ArgumentException or InvalidOperationException or LayoutLimitException)
        {
            reason = $"its counts make no layout ({e.Message})";
            return null;
        }
        if (layout.Fingerprint != fingerprint)
        {
            reason = $"the layout of {thrusters} thrusters, {engines} engines and {gimbals} gimbals has fingerprint 0x{layout.Fingerprint:X8}, not the header's 0x{fingerprint:X8} (edited by hand, or from another game version)";
            return null;
        }
        reason = $"{thrusters} thrusters, {engines} engines, {gimbals} gimbals" + partNote;
        return new BuildTarget(part, layout, $"{target} (from vehicle.h)");
    }

    private static int? Count(string text, string group)
    {
        Match m = Regex.Match(text, $"^#define {group}_COUNT ([0-9]+)[ \\t]*$", RegexOptions.Multiline | RegexOptions.CultureInvariant);
        return m.Success && int.TryParse(m.Groups[1].Value, NumberStyles.None, CultureInfo.InvariantCulture, out int n) ? n : null;
    }

    [GeneratedRegex("^/\\* vehicle\\.h: generated by kFS for (?<target>.+?) \\((?<part>.*)\\), layout 0x(?<fp>[0-9A-Fa-f]{8}), messages\\.json version", RegexOptions.CultureInvariant)]
    private static partial Regex Banner();

    [GeneratedRegex("^#define KFS_LAYOUT_FINGERPRINT 0x(?<fp>[0-9A-Fa-f]{8})u[ \\t]*$", RegexOptions.Multiline | RegexOptions.CultureInvariant)]
    private static partial Regex FingerprintDefine();
}

/// <summary>
/// The <see cref="IKfsLanguageHost"/> of <c>purr-kfs lsp</c> (plan §6.1): the tables of the process's
/// <c>KfsRuntime</c>, a workspace folder, no vehicle and no live program. The build target is, in
/// order: an explicit layout (the <c>--thrusters</c>/<c>--engines</c>/<c>--gimbals</c> flags, bench
/// part); the layout reconstructed from the workspace's <c>vehicle.h</c>
/// (<see cref="VehicleHeaderLayout"/>); else the default layout of <c>purr-kfs check</c> (one thruster,
/// bench part). Without an explicit layout, <c>vehicle.h</c> is watched: a change re-reads it and,
/// when the target differs, raises <see cref="KfsLanguageHost.TargetChanged"/>.
/// </summary>
public sealed class StandaloneLanguageHost : KfsLanguageHost, IDisposable
{
    /// <summary>The header the target is read from, in the workspace root.</summary>
    public const string VehicleHeaderFile = "vehicle.h";

    private readonly LspLogSink _log;
    private readonly bool _explicit;
    private readonly FileSystemWatcher? _watcher;
    private readonly Timer? _settle;
    private readonly object _gate = new();
    private bool _disposed;

    /// <summary>A host over <paramref name="tables"/> for <paramref name="workspaceRoot"/>.</summary>
    /// <param name="tables">The augmented tables (<c>KfsRuntime.Tables</c>).</param>
    /// <param name="workspaceRoot">The workspace folder.</param>
    /// <param name="layout">Explicit layout counts, or null to read <c>vehicle.h</c>.</param>
    /// <param name="token">The token clients must send, or null.</param>
    /// <param name="log">Where the host says which target it uses and why a <c>vehicle.h</c> was rejected.</param>
    /// <param name="watch">Watch <c>vehicle.h</c> for changes (default true; only without an explicit layout).</param>
    public StandaloneLanguageHost(GameTables tables, string workspaceRoot, (int Thrusters, int Engines, int Gimbals)? layout = null,
        string? token = null, LspLogSink? log = null, bool watch = true)
        : base(tables, workspaceRoot, Choose(tables, workspaceRoot, layout, log ?? LspLog.None, out string source), token)
    {
        _log = log ?? LspLog.None;
        _explicit = layout is not null;
        TargetSource = source;
        if (_explicit || !watch) return;
        try
        {
            _settle = new Timer(_ => ReloadFromTimer());
            _watcher = new FileSystemWatcher(WorkspaceRoot, VehicleHeaderFile)
            {
                IncludeSubdirectories = false,
                NotifyFilter = NotifyFilters.FileName | NotifyFilters.LastWrite | NotifyFilters.Size | NotifyFilters.CreationTime,
            };
            _watcher.Changed += OnFileEvent;
            _watcher.Created += OnFileEvent;
            _watcher.Deleted += OnFileEvent;
            _watcher.Renamed += OnFileEvent;
            _watcher.EnableRaisingEvents = true;
        }
        catch (Exception e) when (e is IOException or ArgumentException or PlatformNotSupportedException or UnauthorizedAccessException)
        {
            _log.Safe(LspLogLevel.Warning, $"cannot watch {VehicleHeaderFile} ({e.Message}); restart the server after the next kfs build");
            _watcher?.Dispose();
            _watcher = null;
        }
    }

    /// <summary>Where the current target came from, for messages.</summary>
    public string TargetSource { get; private set; }

    /// <summary>True when <c>vehicle.h</c> is watched.</summary>
    public bool IsWatching => _watcher is not null;

    /// <summary>
    /// Re-reads <c>vehicle.h</c> now (the watcher calls it after a change settles); raises
    /// <see cref="KfsLanguageHost.TargetChanged"/> when the target differs. No-op with an explicit layout.
    /// </summary>
    public void Reload()
    {
        BuildTarget next;
        string source;
        lock (_gate)
        {
            if (_disposed || _explicit) return;
            next = Choose(Tables, WorkspaceRoot, null, _log, out source);
            BuildTarget now = CurrentTarget;
            if (now.Layout.Fingerprint == next.Layout.Fingerprint && now.Part.Name == next.Part.Name && now.DisplayName == next.DisplayName) return;
            TargetSource = source;
        }
        _log.Safe(LspLogLevel.Info, $"build target: {next} — {source}");
        SetTarget(next);
    }

    /// <summary>The settle timer's callback: never throws (an exception on a timer thread ends the process).</summary>
    private void ReloadFromTimer()
    {
        try { Reload(); }
        catch (Exception e) { _log.Safe(LspLogLevel.Error, $"re-reading {VehicleHeaderFile} failed: {e.GetType().Name}: {e.Message}"); }
    }

    /// <inheritdoc/>
    public void Dispose()
    {
        lock (_gate)
        {
            if (_disposed) return;
            _disposed = true;
        }
        _watcher?.Dispose();
        _settle?.Dispose();
    }

    private void OnFileEvent(object sender, FileSystemEventArgs e)
    {
        // Editors and the game write in steps: settle for a moment, then read once. A watcher event
        // runs on a pool thread: nothing may escape it.
        try { _settle?.Change(TimeSpan.FromMilliseconds(100), Timeout.InfiniteTimeSpan); }
        catch (Exception) { /* disposed, or anything else: the next event tries again */ }
    }

    /// <summary>The target by the rules above, and a sentence saying where it came from.</summary>
    public static BuildTarget Choose(GameTables tables, string workspaceRoot, (int Thrusters, int Engines, int Gimbals)? layout, LspLogSink log, out string source)
    {
        ArgumentNullException.ThrowIfNull(tables);
        ArgumentNullException.ThrowIfNull(workspaceRoot);
        ArgumentNullException.ThrowIfNull(log);
        if (layout is { } l)
        {
            source = $"the command line: {l.Thrusters} thrusters, {l.Engines} engines, {l.Gimbals} gimbals";
            return new BuildTarget(tables.BenchPart, LayoutGenerator.Vehicle(VehicleOptions.Name, l.Thrusters, l.Engines, l.Gimbals),
                $"{VehicleOptions.Name} (from the command line)");
        }

        string path = Path.Combine(workspaceRoot, VehicleHeaderFile);
        string? why = null;
        try
        {
            if (File.Exists(path))
            {
                if (VehicleHeaderLayout.Reconstruct(purrTTY.Kfs.Runtime.BoundedFile.ReadText(path, purrTTY.Kfs.Runtime.ProjectResolver.MaxSourceBytes), tables, out string reason) is { } fromHeader)
                {
                    source = $"{VehicleHeaderFile}: {reason}";
                    return fromHeader;
                }
                why = $"{VehicleHeaderFile} is not used: {reason}";
            }
        }
        catch (Exception e) when (e is IOException or UnauthorizedAccessException)
        {
            why = $"{VehicleHeaderFile} cannot be read: {e.Message}";
        }
        if (why is not null) log.Safe(LspLogLevel.Warning, why + "; falling back to the default layout");

        source = (why ?? $"no {VehicleHeaderFile} in the workspace") + "; the default layout of purr-kfs check (1 thruster)";
        return new BuildTarget(tables.BenchPart, LayoutGenerator.Vehicle(VehicleOptions.Name, 1, 0, 0), $"{VehicleOptions.Name} (default layout)");
    }
}
