    /// <summary>The <c>vehicle.h</c> the game's workbench writes for this layout (<c>GeneratedHeaders.Write</c>'s text).</summary>
    private static string VehicleH(IoLayout layout, string target, string part) => GeneratedHeaders.VehicleH(Runtime.Tables, layout, target, part);

    private static uint BannerFingerprint(string header) =>
        uint.Parse(Regex.Match(header, @"^/\* vehicle\.h: generated by kFS for .*, layout 0x([0-9A-F]{8}),").Groups[1].Value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

    private sealed class LogLines
    {
        public readonly List<string> Lines = [];
        public LspLogSink Sink => (level, message) => { lock (Lines) Lines.Add($"{level}: {message}"); };
        public string Text { get { lock (Lines) return string.Join("\n", Lines); } }
    }

    [Test]
    public void Layout_Is_Reconstructed_From_A_Real_Vehicle_H()
    {
        GameTables tables = Runtime.Tables;
        var failures = new List<string>();
        foreach ((int t, int e, int g) in new[] { (1, 0, 0), (4, 1, 1), (8, 2, 3), (2, 0, 4), (12, 4, 0) })
        {
            using var ws = new TempWorkspace();
            IoLayout layout = LayoutGenerator.Vehicle("7", t, e, g);
            string header = VehicleH(layout, "vehicle 7", tables.BenchPart.Name);
            ws.Write("vehicle.h", header);

            using var host = new StandaloneLanguageHost(tables, ws.Root, watch: false);
            uint banner = BannerFingerprint(header);
            uint rebuilt = host.CurrentTarget.Layout.Fingerprint;
            if (rebuilt != banner || banner != layout.Fingerprint) failures.Add($"{t}/{e}/{g}: banner 0x{banner:X8}, rebuilt 0x{rebuilt:X8}, written 0x{layout.Fingerprint:X8}");
            if (host.CurrentTarget.DisplayName != "vehicle 7 (from vehicle.h)") failures.Add($"{t}/{e}/{g}: name {host.CurrentTarget.DisplayName}");
            if (host.CurrentTarget.Part.Name != tables.BenchPart.Name) failures.Add($"{t}/{e}/{g}: part {host.CurrentTarget.Part.Name}");
            if (VehicleHeader.Generate(host.CurrentTarget.Layout, false, tables) != GeneratedHeaders.HeaderBody(header)) failures.Add($"{t}/{e}/{g}: <vehicle.h> text differs");
        }
        Assert.That(failures, Is.Empty, () => string.Join("\n", failures));

        // The bench layout is recognised by its fingerprint; a catalogue part by its name.
        using var bench = new TempWorkspace().Write("vehicle.h", VehicleH(tables.BenchLayout, "bench", tables.Parts[0].Name));
        using var benchHost = new StandaloneLanguageHost(tables, bench.Root, watch: false);
        Assert.That(benchHost.CurrentTarget.Layout, Is.SameAs(tables.BenchLayout));
        Assert.That(benchHost.CurrentTarget.Part.Name, Is.EqualTo(tables.Parts[0].Name));
        Assert.That(benchHost.TargetSource, Does.StartWith("vehicle.h: the bench layout"));

        // CRLF (an editor converted it) still reads.
        using var crlf = new TempWorkspace().Write("vehicle.h", VehicleH(LayoutGenerator.Vehicle("3", 3, 1, 0), "vehicle 3", tables.BenchPart.Name).ReplaceLineEndings("\r\n"));
        using var crlfHost = new StandaloneLanguageHost(tables, crlf.Root, watch: false);
        Assert.That(crlfHost.CurrentTarget.Layout.Fingerprint, Is.EqualTo(LayoutGenerator.Vehicle("x", 3, 1, 0).Fingerprint));
    }

    [Test]
    public void Tampered_Vehicle_H_Is_Rejected_With_A_Logged_Reason()
    {
        GameTables tables = Runtime.Tables;
        uint fallback = LayoutGenerator.Vehicle("sim", 1, 0, 0).Fingerprint;
        string good = VehicleH(LayoutGenerator.Vehicle("7", 4, 1, 1), "vehicle 7", tables.BenchPart.Name);
        foreach ((string what, string text, string reason) in new[]
        {
            ("a count changed", good.Replace("#define THRUSTER_COUNT 4", "#define THRUSTER_COUNT 5"), "has fingerprint 0x"),
            ("the define changed", Regex.Replace(good, "^#define KFS_LAYOUT_FINGERPRINT 0x[0-9A-F]{8}u", "#define KFS_LAYOUT_FINGERPRINT 0xDEADBEEFu", RegexOptions.Multiline), "but KFS_LAYOUT_FINGERPRINT is"),
            ("no fingerprint", "/* hand-written */\n#define THRUSTER_COUNT 4\n", "no '#define KFS_LAYOUT_FINGERPRINT"),
            ("a count missing", good.Replace("#define GIMBAL_COUNT 1\n", ""), "lacks one of"),
        })
        {
            using var ws = new TempWorkspace().Write("vehicle.h", text);
            var log = new LogLines();
            using var host = new StandaloneLanguageHost(tables, ws.Root, log: log.Sink, watch: false);
            Assert.That(host.CurrentTarget.Layout.Fingerprint, Is.EqualTo(fallback), what);
            Assert.That(host.CurrentTarget.DisplayName, Is.EqualTo("sim (default layout)"), what);
            Assert.That(log.Text, Does.Contain("vehicle.h is not used: ").And.Contain(reason).And.Contain("falling back to the default layout"), what);
        }

        // An explicit layout wins over vehicle.h and is not watched.
        using var explicitWs = new TempWorkspace().Write("vehicle.h", good);
        using var explicitHost = new StandaloneLanguageHost(tables, explicitWs.Root, layout: (2, 0, 0));
        Assert.That(explicitHost.CurrentTarget.Layout.Fingerprint, Is.EqualTo(LayoutGenerator.Vehicle("x", 2, 0, 0).Fingerprint));
        Assert.That(explicitHost.IsWatching, Is.False);
    }

    [Test]
    public void Vehicle_H_Change_Raises_TargetChanged()
    {
        GameTables tables = Runtime.Tables;
        using var ws = new TempWorkspace();
        using var host = new StandaloneLanguageHost(tables, ws.Root);
        Assert.That(host.IsWatching, Is.True);
        Assert.That(host.CurrentTarget.DisplayName, Is.EqualTo("sim (default layout)"));
        using var changed = new ManualResetEventSlim(false);
        host.TargetChanged += changed.Set;

        IoLayout layout = LayoutGenerator.Vehicle("9", 6, 2, 2);
        ws.Write("vehicle.h", VehicleH(layout, "vehicle 9", tables.BenchPart.Name));

        Assert.That(changed.Wait(LspTestClient.Timeout), Is.True, "the watcher saw vehicle.h");
        Assert.That(host.CurrentTarget.Layout.Fingerprint, Is.EqualTo(layout.Fingerprint));
        Assert.That(host.CurrentTarget.DisplayName, Is.EqualTo("vehicle 9 (from vehicle.h)"));
    }

    /// <summary>A writer that signals when a line starting with <c>LISTENING </c> was written.</summary>
    private sealed class ListeningWriter : StringWriter
    {
        public readonly ManualResetEventSlim Listening = new(false);
        public int Port;

        public override void WriteLine(string? value)
        {
            base.WriteLine(value);
            if (value is not null && value.StartsWith("LISTENING ", StringComparison.Ordinal))
            {
                Port = int.Parse(value["LISTENING ".Length..], CultureInfo.InvariantCulture);
                Listening.Set();
            }
        }
    }

    private static CliEnvironment Environment(string cwd, CancellationToken stop) =>
        new(name => name == "KSA_DLL_DIR" ? ModuleInit.Directory : null, cwd) { Cancellation = stop };

    [Test]
    public void Cli_Lsp_Listen_End_To_End()
    {
        using var ws = new TempWorkspace().Write("bad.c", Programs.Undeclared);
        using var stop = new CancellationTokenSource();
        var stdout = new ListeningWriter { NewLine = "\n" };
        var stderr = new StringWriter { NewLine = "\n" };
        int exit = -1;
        var cli = new Thread(() => exit = CliApp.Run(["lsp", "--listen", "127.0.0.1:0", "--token", "t0k", "--workspace", ws.Root], stdout, stderr, Environment(ws.Root, stop.Token)))
        {
            IsBackground = true,
        };
        cli.Start();
        try
        {
            Assert.That(stdout.Listening.Wait(LspTestClient.Timeout), Is.True, () => $"no LISTENING line\nstdout: {stdout}\nstderr: {stderr}");
            Assert.That(stdout.ToString(), Is.EqualTo($"LISTENING {stdout.Port}\n"), "one line on stdout");

            using LspTestClient client = ServerProtocolTests.Connect(stdout.Port);
            Assert.That(client.Request("initialize", LspTestClient.InitializeParams("wrong"))["error"], Is.Not.Null, "the token is checked");
            Assert.That(client.WaitForEnd(), Is.True);

            using LspTestClient good = ServerProtocolTests.Connect(stdout.Port);
            good.Initialize("t0k");
            string uri = new WorkspaceUris(ws.Root).ToUri("bad.c");
            good.Open(uri, Programs.Undeclared);
            JsonObject published = good.WaitForDiagnostics(uri, p => p["diagnostics"]!.AsArray().Count > 0);
            Assert.That(published["diagnostics"]![0]!["code"]!.GetValue<string>(), Is.EqualTo("KC-E003"));
            JsonNode range = published["diagnostics"]![0]!["range"]!;
            Assert.That((range["start"]!["line"]!.GetValue<int>(), range["start"]!["character"]!.GetValue<int>(), range["end"]!["character"]!.GetValue<int>()), Is.EqualTo((4, 21, 28)));
            good.ShutdownAndExit();
            Assert.That(good.WaitForEnd(), Is.True);
        }
        finally
        {
            stop.Cancel();
            Assert.That(cli.Join(LspTestClient.Timeout), Is.True, "purr-kfs lsp returns when cancelled");
        }
        Assert.That(exit, Is.EqualTo(CliApp.ExitOk), stderr.ToString);
        Assert.That(stderr.ToString(), Does.Contain("listening on 127.0.0.1:").And.Contain("build target sim (default layout)").And.Not.Contain("Exception"));
        Assert.That(() => { using var late = new TcpClient(); late.Connect(IPAddress.Loopback, stdout.Port); }, Throws.InstanceOf<SocketException>(), "the port is closed");
    }

    [Test]
    public void Cli_Lsp_Stdio_Serves_One_Client()
    {
        using var ws = new TempWorkspace().Write("vehicle.h", VehicleH(LayoutGenerator.Vehicle("5", 4, 0, 0), "vehicle 5", Runtime.Tables.BenchPart.Name));
        var (serverIn, serverOut, clientIn, clientOut, _, _) = MemoryPipe.Duplex();
        var stdout = new StringWriter { NewLine = "\n" };
        var stderr = new StringWriter { NewLine = "\n" };
        CliEnvironment environment = Environment(ws.Root, CancellationToken.None) with { OpenStandardInput = () => serverIn, OpenStandardOutput = () => serverOut };
        int exit = -1;
        var cli = new Thread(() => exit = CliApp.Run(["lsp", "--stdio"], stdout, stderr, environment)) { IsBackground = true };
        cli.Start();

        using (var client = new LspTestClient(clientIn, clientOut))
        {
            client.Initialize();
            string uri = new WorkspaceUris(ws.Root).ToUri("thrusters.c");
            // Clean only on the four-thruster layout recorded in vehicle.h.
            client.Open(uri, "#include <kfs.h>\n#include <vehicle.h>\n#pragma kfs tick_hz 10\n#pragma kfs task run rate_hz=10\n#if THRUSTER_COUNT != 4\n#error \"four\"\n#endif\nvoid run(void) { }\n");
            Assert.That(client.WaitForDiagnostics(uri)["diagnostics"]!.AsArray(), Is.Empty, client.Dump);
            client.ShutdownAndExit();
            Assert.That(client.WaitForEnd(), Is.True);
        }
        Assert.That(cli.Join(LspTestClient.Timeout), Is.True);
        Assert.That(exit, Is.EqualTo(0), stderr.ToString);
        Assert.That(stdout.ToString(), Is.Empty, "nothing but the protocol on stdout");
        Assert.That(stderr.ToString(), Does.Contain("build target vehicle 5 (from vehicle.h)"));
    }

    [Test]
    public void Cli_Lsp_Usage_Errors()
    {
        using var ws = new TempWorkspace();
        foreach ((string[] args, string message) in new[]
        {
            (new[] { "lsp" }, "give exactly one of --stdio and --listen"),
            (new[] { "lsp", "--stdio", "--listen", "127.0.0.1:0" }, "give exactly one of"),
            (new[] { "lsp", "--listen", "0.0.0.0:4000" }, "loopback only"),
            (new[] { "lsp", "--listen", "4000" }, "--listen takes <host>:<port>"),
            (new[] { "lsp", "--listen", "127.0.0.1:99999" }, "is not a port"),
            (new[] { "lsp", "--stdio", "--workspace", ws.Full("missing") }, "is not a folder"),
            (new[] { "lsp", "--stdio", "extra" }, "unexpected argument"),
        })
        {
            CliOutcome r = PurrKfs.Run(args, ws.Root);
            Assert.That(r.ExitCode, Is.EqualTo(CliApp.ExitUsage), r.ToString);
            Assert.That(r.Stderr, Does.Contain(message), r.ToString);
            Assert.That(r.Stdout, Is.Empty);
        }
        Assert.That(PurrKfs.Run(["lsp", "--help"]).Stdout, Does.StartWith("Usage: purr-kfs lsp (--stdio | --listen <host>:<port>)"));
    }
